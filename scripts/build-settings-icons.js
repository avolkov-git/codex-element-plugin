#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const lucide = require("lucide-react");

const root = path.resolve(__dirname, "..");
const names = {
  network: "Network", book: "BookOpen", plug: "Plug", skills: "Sparkles",
  settings: "Settings2", browser: "PanelsTopLeft", play: "Play", search: "Search",
  right: "ChevronRight", down: "ChevronDown", refresh: "RefreshCw", plus: "Plus",
  fileSearch: "FileSearch", close: "X", check: "Check", alert: "CircleAlert",
  trash: "Trash2", download: "Download", external: "ExternalLink", edit: "Pencil"
};
const icons = Object.fromEntries(Object.entries(names).map(([key, name]) => [key,
  renderToStaticMarkup(React.createElement(lucide[name], { size: 18, strokeWidth: 1.75, "aria-hidden": true, focusable: "false" }))
]));
icons.codex = fs.readFileSync(path.join(root, "resources/icons/codex.svg"), "utf8").replace('fill="white"', 'fill="currentColor"');
const output = `/* Generated by scripts/build-settings-icons.js. Lucide icons: ISC license. */\nwindow.__codexElementSettingsIcons = Object.freeze(${JSON.stringify(icons)});\n`;
const target = path.join(root, "media/settings-icons.js");
const license = fs.readFileSync(path.join(path.dirname(require.resolve("lucide-react/package.json")), "LICENSE"), "utf8");
const notices = path.join(root, "media/settings-icons.NOTICES.txt");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output || !fs.existsSync(notices) || fs.readFileSync(notices, "utf8") !== license) {
    throw new Error("Settings icons are out of date. Run npm run build:webview.");
  }
} else {
  fs.writeFileSync(target, output);
  fs.writeFileSync(notices, license);
}
console.log(`Settings icons: ${Math.round(Buffer.byteLength(output) / 1024)} KiB, local asset, no runtime imports`);
